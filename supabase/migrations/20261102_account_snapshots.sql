-- Snapshot diário recuperável de perfil e preferências.
-- O LiveKit nunca escreve nesta tabela e não armazena dados permanentes da conta.
-- Rollback: remover os dois gatilhos, a função private.capture_account_snapshot e a tabela.
begin;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists public.account_data_snapshots (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  snapshot_day date not null default current_date,
  profile_data jsonb not null default '{}'::jsonb,
  settings_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, snapshot_day)
);
create index if not exists account_data_snapshots_user_time_idx
  on public.account_data_snapshots(user_id, snapshot_day desc);

alter table public.account_data_snapshots enable row level security;
revoke all on public.account_data_snapshots from anon, authenticated;
grant select on public.account_data_snapshots to authenticated;

drop policy if exists account_snapshots_read_own on public.account_data_snapshots;
create policy account_snapshots_read_own
on public.account_data_snapshots for select to authenticated
using (user_id = (select auth.uid()));

create or replace function private.capture_account_snapshot()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_user uuid;
  captured_profile jsonb;
  captured_settings jsonb;
begin
  target_user := case when tg_table_name = 'profiles' then new.id else new.user_id end;

  select jsonb_build_object(
    'username', p.username,
    'tag_number', p.tag_number,
    'avatar_url', p.avatar_url,
    'status', p.status,
    'display_name', p.display_name,
    'banner_url', p.banner_url,
    'bio', p.bio,
    'pronouns', p.pronouns,
    'accent_color', p.accent_color,
    'custom_status', p.custom_status,
    'updated_at', p.updated_at
  ) into captured_profile
  from public.profiles p
  where p.id = target_user;

  select jsonb_build_object(
    'version', s.version,
    'settings', s.settings,
    'updated_at', s.updated_at
  ) into captured_settings
  from public.user_settings s
  where s.user_id = target_user;

  insert into public.account_data_snapshots (
    user_id, snapshot_day, profile_data, settings_data, updated_at
  ) values (
    target_user,
    current_date,
    coalesce(captured_profile, '{}'::jsonb),
    coalesce(captured_settings, '{}'::jsonb),
    now()
  )
  on conflict (user_id, snapshot_day) do update
  set profile_data = excluded.profile_data,
      settings_data = excluded.settings_data,
      updated_at = excluded.updated_at;

  return new;
end;
$$;

revoke all on function private.capture_account_snapshot() from public, anon, authenticated;

drop trigger if exists profiles_capture_account_snapshot on public.profiles;
create trigger profiles_capture_account_snapshot
after insert or update on public.profiles
for each row execute function private.capture_account_snapshot();

drop trigger if exists settings_capture_account_snapshot on public.user_settings;
create trigger settings_capture_account_snapshot
after insert or update on public.user_settings
for each row execute function private.capture_account_snapshot();

insert into public.account_data_snapshots (
  user_id, snapshot_day, profile_data, settings_data, updated_at
)
select
  p.id,
  current_date,
  jsonb_build_object(
    'username', p.username,
    'tag_number', p.tag_number,
    'avatar_url', p.avatar_url,
    'status', p.status,
    'display_name', p.display_name,
    'banner_url', p.banner_url,
    'bio', p.bio,
    'pronouns', p.pronouns,
    'accent_color', p.accent_color,
    'custom_status', p.custom_status,
    'updated_at', p.updated_at
  ),
  case when s.user_id is null then '{}'::jsonb else jsonb_build_object(
    'version', s.version,
    'settings', s.settings,
    'updated_at', s.updated_at
  ) end,
  now()
from public.profiles p
left join public.user_settings s on s.user_id = p.id
on conflict (user_id, snapshot_day) do update
set profile_data = excluded.profile_data,
    settings_data = excluded.settings_data,
    updated_at = excluded.updated_at;

notify pgrst, 'reload schema';
commit;
