create table if not exists public.signup_invite_usage (
  id bigint generated by default as identity primary key,
  invite_hash text not null check (char_length(invite_hash) = 64),
  attempted_at timestamptz not null default now()
);

alter table public.signup_invite_usage enable row level security;
revoke all on table public.signup_invite_usage from anon, authenticated;
grant select, insert, delete on table public.signup_invite_usage to service_role;
grant usage, select on sequence public.signup_invite_usage_id_seq to service_role;

create index if not exists signup_invite_usage_lookup_idx
  on public.signup_invite_usage (invite_hash, attempted_at desc);

create policy "signup_invite_usage_denied_to_clients"
on public.signup_invite_usage
for all
to anon, authenticated
using (false)
with check (false);

comment on table public.signup_invite_usage is
  'Rate limit técnico do cadastro temporário por convite; não armazena IP, e-mail ou senha.';
